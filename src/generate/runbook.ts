import { solverLabel } from '../analyze/solvers.js';
import type { CallbackSpec, Plan, Step, StepCurl } from '../model/types.js';
import { curlSet, expectedAfter, literalCurl, realmPath, stepTitle } from './curl.js';

export { realmPath } from './curl.js';

export interface RunbookOptions {
  tenant?: string;
  realm?: string;
  source?: string;
  sessionJourney?: string;
}

const md = (s: string) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');
const code = (lang: string, text: string) => `\`\`\`${lang}\n${text}\n\`\`\``;

function inputsTable(cbs: CallbackSpec[]): string {
  const rows: string[] = [];
  for (const cb of cbs) {
    for (const i of cb.inputs) {
      if (i.kind === 'fixed') continue;
      const how = i.solver ? solverLabel(i.solver) : i.variable ? `\`${i.variable}\`` : 'sent back unchanged';
      rows.push(`| \`${i.name}\` | ${cb.type}${cb.prompt ? ` "${md(cb.prompt)}"` : ''} | ${how} |`);
    }
  }
  if (!rows.length) return '_No inputs: post the response back as received._';
  return ['| Input | Callback | Value |', '| --- | --- | --- |', ...rows].join('\n');
}

function bodySection(url: string, sc: StepCurl, isPage: boolean): string[] {
  if (!sc.body) return [];
  return [
    '<details><summary>What is sent (Postman-style body)</summary>',
    '',
    isPage
      ? 'Page Node callbacks carry an `_id`: send back the value from the response (it can change between responses).'
      : 'Values in `<...>` come from the variables above or from the last response.',
    '',
    code('bash', literalCurl(url, sc.body)),
    '',
    '</details>',
    '',
  ];
}

function stepSection(step: Step, sc: StepCurl, url: string): string {
  const out: string[] = [];
  out.push(`## ${stepTitle(step)} (${step.kind})`);
  out.push('');
  out.push(`> ${step.plainText}`);
  out.push('');
  if (step.condition) {
    out.push(`**Optional:** appears only when ${step.condition}. Skip this step if the response has other callbacks.`);
    out.push('');
  }
  if (step.kind === 'variant') {
    out.push(
      `${step.notes?.[0] ?? 'The server decides at run time'}, so it sends one of these. Check which one you got:`,
    );
    out.push('');
    out.push(code('bash', `jq -r '[.callbacks[]?.type] | join(",")' <<<"$RESP"`));
    out.push('');
    (step.variants ?? []).forEach((v, k) => {
      out.push(`### Variant \`${v.label}\`: \`${v.signature}\`${v.solver ? ` (${solverLabel(v.solver)})` : ''}`);
      out.push('');
      if (v.kind !== 'suspend' && v.kind !== 'manual') {
        out.push(inputsTable(v.callbacks));
        out.push('');
      }
      const block = sc.run[k];
      if (block) out.push(code('bash', block.code));
      out.push('');
    });
  } else {
    if (step.kind !== 'suspend' && step.kind !== 'manual') {
      out.push(inputsTable(step.callbacks));
      out.push('');
    }
    for (const b of sc.run) {
      out.push(code('bash', b.code));
      out.push('');
    }
  }
  out.push(...bodySection(url, sc, step.nodeType === 'PageNode'));
  const notes = step.kind === 'variant' || step.kind === 'manual' ? [] : (step.notes ?? []);
  for (const n of notes) out.push(`- ${n}`);
  if (notes.length) out.push('');
  out.push(`**Expected next:** ${sc.expect}`);
  return out.join('\n');
}

/**
 * Render `<journey>.runbook.md`: copy each block and run it in order in one bash terminal.
 * Every block posts the last response back with its inputs filled, so `_id`s and server values are kept.
 */
export function generateRunbook(plan: Plan, opts: RunbookOptions = {}): string {
  const set = curlSet({ ...plan, withSession: plan.withSession ?? opts.sessionJourney }, opts);
  const url = `$TENANT/am/json/${realmPath(opts.realm)}/authenticate?authIndexType=service&authIndexValue=${encodeURIComponent(plan.journey)}`;
  const out: string[] = [];
  out.push(`# ${plan.journey} – runbook`);
  out.push('');
  out.push(
    `Generated by bkj2c from \`${opts.source ?? 'a journey export'}\`. Target: **${plan.target === 'success' ? 'Success' : 'Failure'}** · Coverage: **${plan.coverage.toUpperCase()}** · Steps: **${plan.steps.length}**`,
  );
  out.push('');
  for (const n of plan.coverageNotes) out.push(`- ${n}`);
  if (plan.coverageNotes.length) out.push('');
  out.push('Copy the blocks one by one into the same bash terminal (Git Bash works; needs `curl` and `jq`).');
  out.push(
    'Each block posts the last response (`$RESP`) back with the inputs filled in, then prints the new response.',
  );
  out.push('');
  out.push('## Setup');
  out.push('');
  out.push(code('bash', set.setup.code));
  out.push('');
  if (plan.inputs.length) {
    out.push('| Variable | Default | Used for |');
    out.push('| --- | --- | --- |');
    for (const i of plan.inputs) {
      out.push(
        `| \`${i.variable}\` | ${i.secret ? '_(secret)_' : `\`${md(i.defaultValue) || ' '}\``} | ${md(i.description)} |`,
      );
    }
    out.push('');
  }
  out.push('## Start');
  out.push('');
  out.push(code('bash', set.start.code));
  out.push('');
  out.push(`**Expected next:** ${expectedAfter(plan, -1)}`);
  plan.steps.forEach((s, i) => {
    out.push('');
    const sc = set.steps[i];
    if (sc) out.push(stepSection(s, sc, url));
  });
  out.push('');
  out.push('## Finish');
  out.push('');
  out.push(code('bash', set.finish.code));
  if (plan.target === 'success') {
    out.push('');
    out.push(code('bash', set.session.code));
  }
  if (plan.warnings.length) {
    out.push('');
    out.push('## Warnings');
    out.push('');
    for (const w of plan.warnings) out.push(`- **${w.level}** ${md(w.message)}`);
  }
  return `${out.join('\n')}\n`;
}
