import { render } from 'preact';
import type { ViewerData } from '../../src/model/types';
import { App } from './App';
import './styles.css';

function readData(): ViewerData | undefined {
  const el = document.getElementById('bkj2c-data');
  const text = el?.textContent?.trim() ?? '';
  if (!text.startsWith('{')) return undefined; // placeholder: the page was not generated by bkj2c
  try {
    return JSON.parse(text) as ViewerData;
  } catch {
    return undefined;
  }
}

const root = document.getElementById('app');
const data = readData();
if (root) {
  if (data) render(<App data={data} />, root);
  else root.innerHTML = '<p class="empty">No journey data in this page. Generate it with <code>bkj2c gen</code>.</p>';
}
